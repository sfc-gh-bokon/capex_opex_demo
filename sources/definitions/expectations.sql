-- Data-quality expectations (Data Metric Functions)

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.ROW_COUNT
    TO TABLE CAPEX_{{env}}.BRONZE.RAW_RECORDS
    ON ()
    EXPECTATION BRONZE_HAS_DATA (value > 0);

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.FRESHNESS
    TO TABLE CAPEX_{{env}}.BRONZE.RAW_RECORDS
    ON (INGESTED_TS)
    EXPECTATION LANDED_WITHIN_2_PULLS (value < 3600);

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT
    TO DYNAMIC TABLE CAPEX_{{env}}.SILVER.COST_LINE
    ON (AMOUNT)
    EXPECTATION AMOUNT_PARSEABLE (value = 0);

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.DUPLICATE_COUNT
    TO DYNAMIC TABLE CAPEX_{{env}}.SILVER.COST_LINE
    ON (COST_LINE_ID)
    EXPECTATION ONE_ROW_PER_COST_LINE (value = 0);

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT
    TO DYNAMIC TABLE CAPEX_{{env}}.SILVER.COST_LINE
    ON (COST_CENTER)
    EXPECTATION NO_ORPHAN_PROJECTS (value = 0);

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.MIN
    TO DYNAMIC TABLE CAPEX_{{env}}.GOLD.PROJECT_FINANCIALS
    ON (TOTAL_SPEND)
    EXPECTATION SPEND_NOT_NEGATIVE (value >= 0);
