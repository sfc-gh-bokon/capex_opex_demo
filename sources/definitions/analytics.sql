DEFINE DYNAMIC TABLE CAPEX_{{env}}.GOLD.RULE_EVALUATION
WAREHOUSE = CAPEX_{{env}}_WH
TARGET_LAG = '{{gold_lag}}'
INITIALIZE = 'ON_CREATE'
COMMENT = 'Applies the active, approved criteria version to every valid cost line'
AS
WITH active AS (
    SELECT CONFIG_VALUE AS CRITERIA_VERSION
    FROM CAPEX_{{env}}.CONTROL.ACTIVE_CONFIG WHERE CONFIG_KEY = 'CRITERIA_VERSION'
),
rules AS (
    SELECT r.* FROM CAPEX_{{env}}.CONTROL.CLASSIFICATION_CRITERIA r
    JOIN active a ON a.CRITERIA_VERSION = r.CRITERIA_VERSION
    WHERE r.STATUS = 'APPROVED'
),
lines AS (
    SELECT * FROM CAPEX_{{env}}.SILVER.COST_LINE_EVIDENCE WHERE IS_VALID
),
matched AS (
    SELECT l.COST_LINE_ID, r.RULE_ID, r.RULE_NAME, r.PRIORITY, r.IMPLIED_CLASS, r.RULE_ACTION,
           r.RATIONALE, r.POLICY_REFERENCE, r.CRITERIA_VERSION
    FROM lines l
    JOIN rules r ON REGEXP_INSTR(l.EVIDENCE_TEXT, r.MATCH_PATTERN, 1, 1, 0, 'i') > 0
    QUALIFY ROW_NUMBER() OVER (PARTITION BY l.COST_LINE_ID ORDER BY r.PRIORITY) = 1
)
SELECT
    l.COST_LINE_ID, l.PROJECT_ID, l.PROJECT_NAME, l.COST_CENTER, l.COST_TYPE, l.GL_ACCOUNT,
    l.RECORDED_CLASS, l.AMOUNT, l.FISCAL_MONTH, l.DESCRIPTION, l.EVIDENCE_TEXT, l.EVIDENCE_HASH,
    l.EVIDENCE_UPDATED_TS, l.SOURCE_UPDATED_TS,
    (SELECT CRITERIA_VERSION FROM active) AS CRITERIA_VERSION,
    m.RULE_ID, m.RULE_NAME, m.RATIONALE AS RULE_RATIONALE, m.POLICY_REFERENCE,
    IFF(m.RULE_ACTION = 'INSUFFICIENT', 'INSUFFICIENT EVIDENCE', m.IMPLIED_CLASS) AS RULE_IMPLIED_CLASS,
    CASE
        WHEN m.RULE_ID IS NULL THEN 'NO_RULE_MATCHED'
        WHEN m.RULE_ACTION = 'INSUFFICIENT' THEN 'NEEDS_EVIDENCE'
        WHEN m.IMPLIED_CLASS <> l.RECORDED_CLASS THEN 'POTENTIAL_RECLASS_' || l.RECORDED_CLASS || '_TO_' || m.IMPLIED_CLASS
        ELSE 'CONSISTENT'
    END AS RULE_OUTCOME,
    RULE_OUTCOME LIKE 'POTENTIAL_RECLASS%' OR RULE_OUTCOME = 'NEEDS_EVIDENCE' AS NEEDS_REVIEW
FROM lines l
LEFT JOIN matched m ON m.COST_LINE_ID = l.COST_LINE_ID;

DEFINE VIEW CAPEX_{{env}}.GOLD.RECONCILIATION
COMMENT = 'Source-to-report reconciliation: Bronze (latest) = Silver = Gold + DQ exclusions'
AS
WITH bronze AS (
    SELECT COUNT(*) AS N
    FROM (SELECT SOURCE_RECORD_ID FROM CAPEX_{{env}}.BRONZE.RAW_RECORDS
          WHERE SOURCE_SYSTEM = 'CLARITY' AND ENTITY = 'cost_line'
          GROUP BY SOURCE_RECORD_ID)
),
silver AS (
    SELECT COUNT(*) AS N, COUNT_IF(IS_VALID) AS N_VALID, COUNT_IF(NOT IS_VALID) AS N_EXCLUDED,
           SUM(IFF(IS_VALID, AMOUNT, 0)) AS VALID_AMOUNT
    FROM CAPEX_{{env}}.SILVER.COST_LINE
),
gold AS (
    SELECT SUM(COST_LINES) AS N, SUM(TOTAL_SPEND) AS AMOUNT FROM CAPEX_{{env}}.GOLD.PROJECT_FINANCIALS
)
SELECT
    bronze.N AS BRONZE_DISTINCT_COST_LINES,
    silver.N AS SILVER_COST_LINES,
    silver.N_EXCLUDED AS DQ_EXCLUDED_LINES,
    gold.N AS GOLD_COST_LINES,
    silver.VALID_AMOUNT AS SILVER_VALID_AMOUNT,
    gold.AMOUNT AS GOLD_AMOUNT,
    bronze.N = silver.N
        AND silver.N_VALID = gold.N
        AND silver.VALID_AMOUNT = gold.AMOUNT AS IS_RECONCILED
FROM bronze, silver, gold;

DEFINE VIEW CAPEX_{{env}}.CONTROL.INGEST_STATUS
COMMENT = 'Latest pull per source/entity: source vs Snowflake timestamps and run status'
AS
SELECT l.SOURCE_SYSTEM, l.ENTITY, l.STATUS, l.STARTED_TS, l.ENDED_TS,
       DATEDIFF('second', l.STARTED_TS, l.ENDED_TS) AS DURATION_S,
       l.PAGES, l.API_RETRIES, l.RECORDS_RECEIVED, l.RECORDS_NEW_OR_CHANGED, l.RECORDS_UNCHANGED,
       w.HIGH_WATERMARK_TS AS SOURCE_LAST_UPDATED_LANDED,
       w.UPDATED_TS AS SNOWFLAKE_RECEIVED_TS,
       l.ERROR_MESSAGE
FROM CAPEX_{{env}}.CONTROL.INGEST_RUN_LOG l
LEFT JOIN CAPEX_{{env}}.CONTROL.SOURCE_WATERMARK w
  ON w.SOURCE_SYSTEM = l.SOURCE_SYSTEM AND w.ENTITY = l.ENTITY
QUALIFY ROW_NUMBER() OVER (PARTITION BY l.SOURCE_SYSTEM, l.ENTITY ORDER BY l.STARTED_TS DESC) = 1;

