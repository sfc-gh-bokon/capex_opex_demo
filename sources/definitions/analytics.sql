DEFINE VIEW CAPEX_{{env}}.REVIEW.REVIEW_QUEUE
COMMENT = 'Current suggestion per cost line with its latest reviewer decision'
AS
WITH latest_decision AS (
    SELECT * FROM CAPEX_{{env}}.REVIEW.DECISION_HISTORY
    QUALIFY ROW_NUMBER() OVER (PARTITION BY SUGGESTION_ID ORDER BY DECIDED_TS DESC) = 1
)
SELECT
    s.SUGGESTION_ID, s.COST_LINE_ID, s.PROJECT_ID, r.PROJECT_NAME, r.COST_CENTER, r.COST_TYPE,
    r.AMOUNT, r.FISCAL_MONTH, r.DESCRIPTION,
    s.RECORDED_CLASS AS CURRENT_CLASSIFICATION,
    s.PROPOSED_CLASS AS PROPOSED_CLASSIFICATION,
    s.RULE_ID, s.RULE_NAME AS TRIGGERING_CRITERIA, r.RULE_OUTCOME, r.POLICY_REFERENCE,
    s.RULE_IMPLIED_CLASS, s.AI_CLASSIFY_LABEL, s.AI_COMPLETE_LABEL,
    (s.AI_CLASSIFY_LABEL = s.AI_COMPLETE_LABEL) AS AI_METHODS_AGREE,
    (s.AI_COMPLETE_LABEL = s.RULE_IMPLIED_CLASS) AS AI_AGREES_WITH_RULE,
    s.CONFIDENCE, s.RATIONALE, s.EVIDENCE_QUOTES, r.EVIDENCE_TEXT AS SUPPORTING_EVIDENCE,
    s.CRITERIA_VERSION, s.MODEL, s.PROMPT_VERSION, s.CREATED_TS AS SUGGESTED_TS,
    COALESCE(d.DECISION, 'PENDING') AS REVIEW_STATUS,
    d.DECIDED_BY, d.DECIDED_TS, d.REVIEWER_COMMENT
FROM CAPEX_{{env}}.REVIEW.AI_SUGGESTION s
LEFT JOIN CAPEX_{{env}}.GOLD.RULE_EVALUATION r ON r.COST_LINE_ID = s.COST_LINE_ID
LEFT JOIN latest_decision d ON d.SUGGESTION_ID = s.SUGGESTION_ID
WHERE s.SUPERSEDED_TS IS NULL;

