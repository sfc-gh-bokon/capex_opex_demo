AS
SELECT PROJECT_ID, PROJECT_NAME, BUSINESS_UNIT, COST_CENTER, FISCAL_MONTH,
       SUM(IFF(RECORDED_CLASS = 'CAPEX', AMOUNT, 0)) AS RECORDED_CAPEX,
       SUM(IFF(RECORDED_CLASS = 'OPEX', AMOUNT, 0))  AS RECORDED_OPEX,
