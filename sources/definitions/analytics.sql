DEFINE DYNAMIC TABLE CAPEX_{{env}}.SILVER.COST_LINE_EVIDENCE
WAREHOUSE = CAPEX_{{env}}_WH
TARGET_LAG = 'DOWNSTREAM'
INITIALIZE = 'ON_CREATE'
COMMENT = 'Cost line joined to supporting descriptive evidence from Azure DevOps and ServiceNow'
AS
WITH ado AS (
    SELECT COST_LINE_ID,
           LISTAGG('ADO ' || WORK_ITEM_ID || ' [' || WORK_ITEM_TYPE || '] ' || TITLE || ': ' || DESCRIPTION, ' || ')
               WITHIN GROUP (ORDER BY WORK_ITEM_ID) AS ADO_EVIDENCE,
           MAX(SOURCE_UPDATED_TS) AS ADO_UPDATED_TS
    FROM CAPEX_{{env}}.SILVER.WORK_ITEM GROUP BY COST_LINE_ID
),
snow AS (
    SELECT COST_LINE_ID,
           LISTAGG('ServiceNow ' || RECORD_NUMBER || ': ' || SHORT_DESCRIPTION || ' - ' || DESCRIPTION, ' || ')
               WITHIN GROUP (ORDER BY RECORD_NUMBER) AS SNOW_EVIDENCE,
           MAX(SOURCE_UPDATED_TS) AS SNOW_UPDATED_TS
    FROM CAPEX_{{env}}.SILVER.SERVICENOW_RECORD GROUP BY COST_LINE_ID
)
SELECT
    c.*,
    a.ADO_EVIDENCE,
    s.SNOW_EVIDENCE,
    'Clarity: ' || c.DESCRIPTION
        || COALESCE(' || ' || a.ADO_EVIDENCE, '')
        || COALESCE(' || ' || s.SNOW_EVIDENCE, '') AS EVIDENCE_TEXT,
    SHA2(EVIDENCE_TEXT || '|' || COALESCE(c.RECORDED_CLASS, '')) AS EVIDENCE_HASH,
    GREATEST(c.SOURCE_UPDATED_TS, COALESCE(a.ADO_UPDATED_TS, c.SOURCE_UPDATED_TS),
             COALESCE(s.SNOW_UPDATED_TS, c.SOURCE_UPDATED_TS)) AS EVIDENCE_UPDATED_TS
FROM CAPEX_{{env}}.SILVER.COST_LINE c
LEFT JOIN ado a ON a.COST_LINE_ID = c.COST_LINE_ID
LEFT JOIN snow s ON s.COST_LINE_ID = c.COST_LINE_ID;

DEFINE DYNAMIC TABLE CAPEX_{{env}}.SILVER.DQ_EXCEPTIONS
WAREHOUSE = CAPEX_{{env}}_WH
TARGET_LAG = '{{gold_lag}}'
INITIALIZE = 'ON_CREATE'
COMMENT = 'One row per data-quality exception; excluded rows stay traceable to Bronze'
AS
SELECT 'CLARITY' AS SOURCE_SYSTEM, 'cost_line' AS ENTITY, c.COST_LINE_ID AS RECORD_ID,
       f.value::VARCHAR AS ISSUE, 'EXCLUDED_FROM_GOLD' AS HANDLING,
       OBJECT_CONSTRUCT('amount', c.SOURCE_AMOUNT, 'invoice_date', c.SOURCE_INVOICE_DATE,
                        'project_id', c.PROJECT_ID) AS SOURCE_VALUES,
       c.SOURCE_UPDATED_TS, c.INGESTED_TS, c.RUN_ID
FROM CAPEX_{{env}}.SILVER.COST_LINE c, LATERAL FLATTEN(INPUT => c.DQ_ISSUES) f
UNION ALL
SELECT SOURCE_SYSTEM, ENTITY, SOURCE_RECORD_ID, 'DUPLICATE_DELIVERY', 'DEDUPLICATED',
       OBJECT_CONSTRUCT('deliveries', COUNT(*), 'distinct_payloads', COUNT(DISTINCT PAYLOAD_HASH)),
       MAX(SOURCE_UPDATED_TS), MAX(INGESTED_TS), MAX(RUN_ID)
FROM CAPEX_{{env}}.BRONZE.RAW_RECORDS
GROUP BY SOURCE_SYSTEM, ENTITY, SOURCE_RECORD_ID, SOURCE_UPDATED_TS
HAVING COUNT(*) > 1;

