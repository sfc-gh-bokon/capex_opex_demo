DEFINE TAG CAPEX_{{env}}.GOVERNANCE.SENSITIVITY
    ALLOWED_VALUES 'PII', 'CONFIDENTIAL_RATE'
    COMMENT = 'Column sensitivity classification; drives tag-based masking';

DEFINE MASKING POLICY CAPEX_{{env}}.GOVERNANCE.MASK_SENSITIVE_STRING
    AS (VAL STRING) RETURNS STRING ->
    CASE
        WHEN IS_ROLE_IN_SESSION('CAPEX_{{env}}_DEPLOYER') OR IS_ROLE_IN_SESSION('CAPEX_FIN_REVIEWER') THEN VAL
        WHEN VAL IS NULL THEN NULL
        ELSE '*** MASKED ***'
    END
    COMMENT = 'PII strings (contractor names) visible only to Finance reviewers and the pipeline owner';

DEFINE MASKING POLICY CAPEX_{{env}}.GOVERNANCE.MASK_SENSITIVE_NUMBER
    AS (VAL NUMBER(10,2)) RETURNS NUMBER(10,2) ->
    CASE
        WHEN IS_ROLE_IN_SESSION('CAPEX_{{env}}_DEPLOYER') OR IS_ROLE_IN_SESSION('CAPEX_FIN_REVIEWER')
             OR IS_ROLE_IN_SESSION('CAPEX_FIN_ANALYST') THEN VAL
        ELSE NULL
    END
    COMMENT = 'Contractor hourly rates visible only to Finance roles and the pipeline owner';

DEFINE TABLE CAPEX_{{env}}.GOVERNANCE.COST_CENTER_ACCESS (
    ROLE_NAME         VARCHAR,
    COST_CENTER       VARCHAR
) COMMENT = 'Row-level entitlements: which roles may see which cost centers';

DEFINE ROW ACCESS POLICY CAPEX_{{env}}.GOVERNANCE.RAP_COST_CENTER
    AS (CC VARCHAR) RETURNS BOOLEAN ->
    IS_ROLE_IN_SESSION('CAPEX_{{env}}_DEPLOYER')
    OR IS_ROLE_IN_SESSION('CAPEX_FIN_REVIEWER')
    OR IS_ROLE_IN_SESSION('CAPEX_FIN_ANALYST')
    OR EXISTS (SELECT 1 FROM CAPEX_{{env}}.GOVERNANCE.COST_CENTER_ACCESS a
               WHERE a.ROLE_NAME = CURRENT_ROLE() AND a.COST_CENTER = CC)
    COMMENT = 'Finance sees all cost centers; other teams see only their mapped cost centers';
