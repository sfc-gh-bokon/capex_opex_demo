DEFINE DYNAMIC TABLE CAPEX_{{env}}.SILVER.PROJECT
WAREHOUSE = CAPEX_{{env}}_WH
TARGET_LAG = 'DOWNSTREAM'
INITIALIZE = 'ON_CREATE'
COMMENT = 'Latest version of each Clarity project; project codes standardized to PRJnnnn'
AS
SELECT
    'PRJ' || LPAD(REGEXP_SUBSTR(PAYLOAD:PROJECT_CODE::VARCHAR, '[0-9]+'), 4, '0') AS PROJECT_ID,
    PAYLOAD:PROJECT_CODE::VARCHAR                  AS SOURCE_PROJECT_CODE,
    PAYLOAD:PROJECT_NAME::VARCHAR                  AS PROJECT_NAME,
    PAYLOAD:PORTFOLIO::VARCHAR                     AS PORTFOLIO,
    PAYLOAD:BUSINESS_UNIT::VARCHAR                 AS BUSINESS_UNIT,
    PAYLOAD:COST_CENTER::VARCHAR                   AS COST_CENTER,
    PAYLOAD:PROJECT_MANAGER::VARCHAR               AS PROJECT_MANAGER,
    PAYLOAD:LIFECYCLE_PHASE::VARCHAR               AS LIFECYCLE_PHASE,
    TRY_TO_DATE(PAYLOAD:START_DATE::VARCHAR)       AS START_DATE,
    PAYLOAD:STATUS::VARCHAR                        AS STATUS,
    SOURCE_UPDATED_TS,
    INGESTED_TS
FROM CAPEX_{{env}}.BRONZE.RAW_RECORDS
WHERE SOURCE_SYSTEM = 'CLARITY' AND ENTITY = 'project'
QUALIFY ROW_NUMBER() OVER (PARTITION BY SOURCE_RECORD_ID ORDER BY SOURCE_UPDATED_TS DESC, INGESTED_TS DESC) = 1;

DEFINE DYNAMIC TABLE CAPEX_{{env}}.SILVER.COST_LINE
WAREHOUSE = CAPEX_{{env}}_WH
TARGET_LAG = 'DOWNSTREAM'
INITIALIZE = 'ON_CREATE'
DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES'
COMMENT = 'Latest version of each Clarity cost line with typed amounts/dates and DQ flags'
AS
WITH latest AS (
    SELECT *
    FROM CAPEX_{{env}}.BRONZE.RAW_RECORDS
    WHERE SOURCE_SYSTEM = 'CLARITY' AND ENTITY = 'cost_line'
    QUALIFY ROW_NUMBER() OVER (PARTITION BY SOURCE_RECORD_ID ORDER BY SOURCE_UPDATED_TS DESC, INGESTED_TS DESC) = 1
),
typed AS (
    SELECT
        PAYLOAD:COST_LINE_ID::VARCHAR                                            AS COST_LINE_ID,
        'PRJ' || LPAD(REGEXP_SUBSTR(PAYLOAD:PROJECT_CODE::VARCHAR, '[0-9]+'), 4, '0') AS PROJECT_ID,
        PAYLOAD:GL_ACCOUNT::VARCHAR                                              AS GL_ACCOUNT,
        INITCAP(TRIM(PAYLOAD:COST_TYPE::VARCHAR))                                AS COST_TYPE,
        UPPER(TRIM(PAYLOAD:RECORDED_CLASS::VARCHAR))                             AS RECORDED_CLASS,
        PAYLOAD:AMOUNT::VARCHAR                                                  AS SOURCE_AMOUNT,
        TRY_TO_NUMBER(REPLACE(PAYLOAD:AMOUNT::VARCHAR, ',', ''), 18, 2)          AS AMOUNT,
        PAYLOAD:CURRENCY::VARCHAR                                                AS CURRENCY,
        TRY_TO_DATE(PAYLOAD:FISCAL_PERIOD::VARCHAR || '-01')                     AS FISCAL_MONTH,
        PAYLOAD:INVOICE_DATE::VARCHAR                                            AS SOURCE_INVOICE_DATE,
        COALESCE(TRY_TO_DATE(PAYLOAD:INVOICE_DATE::VARCHAR, 'YYYY-MM-DD'),
                 TRY_TO_DATE(PAYLOAD:INVOICE_DATE::VARCHAR, 'MM/DD/YYYY'))       AS INVOICE_DATE,
        PAYLOAD:VENDOR::VARCHAR                                                  AS VENDOR,
        PAYLOAD:CONTRACTOR_NAME::VARCHAR                                         AS CONTRACTOR_NAME,
        TRY_TO_NUMBER(PAYLOAD:HOURLY_RATE::VARCHAR, 10, 2)                       AS HOURLY_RATE,
        PAYLOAD:DESCRIPTION::VARCHAR                                             AS DESCRIPTION,
        PAYLOAD:WORK_PHASE::VARCHAR                                              AS WORK_PHASE,
        SOURCE_UPDATED_TS,
        INGESTED_TS,
        RUN_ID,
        PAYLOAD_HASH
    FROM latest
)
SELECT
    t.*,
    p.PROJECT_NAME,
    p.BUSINESS_UNIT,
    p.COST_CENTER,
    ARRAY_CONSTRUCT_COMPACT(
        IFF(t.AMOUNT IS NULL, 'AMOUNT_UNPARSEABLE', NULL),
        IFF(t.INVOICE_DATE IS NULL, 'INVOICE_DATE_UNPARSEABLE', NULL),
        IFF(p.PROJECT_ID IS NULL, 'ORPHAN_PROJECT', NULL),
        IFF(t.RECORDED_CLASS NOT IN ('CAPEX', 'OPEX'), 'UNKNOWN_CLASS', NULL)
    ) AS DQ_ISSUES,
    ARRAY_SIZE(DQ_ISSUES) = 0 AS IS_VALID
FROM typed t
LEFT JOIN CAPEX_{{env}}.SILVER.PROJECT p ON p.PROJECT_ID = t.PROJECT_ID;

