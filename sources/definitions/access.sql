-- Access control
-- Database roles = access roles (what can be touched), scoped to this environment's database.
-- Account roles  = functional roles (who people are), created once in sql/00_platform_setup.sql.
-- The same functional role maps to different access in DEV vs UAT/PROD via templating.

DEFINE DATABASE ROLE CAPEX_{{env}}.GOLD_READER
    COMMENT = 'Read published Gold analytics';

DEFINE DATABASE ROLE CAPEX_{{env}}.REVIEWER
    COMMENT = 'Read review queue and record decisions (append-only)';

DEFINE DATABASE ROLE CAPEX_{{env}}.PIPELINE_OBSERVER
    COMMENT = 'Read Bronze/Silver/Control for support and troubleshooting';

-- ---------- GOLD_READER ----------
GRANT USAGE ON DATABASE CAPEX_{{env}} TO DATABASE ROLE CAPEX_{{env}}.GOLD_READER;
GRANT USAGE ON SCHEMA CAPEX_{{env}}.GOLD TO DATABASE ROLE CAPEX_{{env}}.GOLD_READER;
GRANT SELECT ON DYNAMIC TABLE CAPEX_{{env}}.GOLD.PROJECT_FINANCIALS TO DATABASE ROLE CAPEX_{{env}}.GOLD_READER;
GRANT SELECT ON DYNAMIC TABLE CAPEX_{{env}}.GOLD.COST_LINE_DETAIL TO DATABASE ROLE CAPEX_{{env}}.GOLD_READER;

-- ---------- REVIEWER (inherits GOLD_READER) ----------
GRANT DATABASE ROLE CAPEX_{{env}}.GOLD_READER TO DATABASE ROLE CAPEX_{{env}}.REVIEWER;
GRANT USAGE ON SCHEMA CAPEX_{{env}}.REVIEW TO DATABASE ROLE CAPEX_{{env}}.REVIEWER;
GRANT USAGE ON SCHEMA CAPEX_{{env}}.CONTROL TO DATABASE ROLE CAPEX_{{env}}.REVIEWER;
GRANT SELECT ON DYNAMIC TABLE CAPEX_{{env}}.GOLD.RULE_EVALUATION TO DATABASE ROLE CAPEX_{{env}}.REVIEWER;
GRANT SELECT ON VIEW CAPEX_{{env}}.GOLD.RECONCILIATION TO DATABASE ROLE CAPEX_{{env}}.REVIEWER;
GRANT SELECT ON VIEW CAPEX_{{env}}.REVIEW.REVIEW_QUEUE TO DATABASE ROLE CAPEX_{{env}}.REVIEWER;
GRANT SELECT ON TABLE CAPEX_{{env}}.REVIEW.AI_SUGGESTION TO DATABASE ROLE CAPEX_{{env}}.REVIEWER;
GRANT SELECT ON TABLE CAPEX_{{env}}.REVIEW.DECISION_HISTORY TO DATABASE ROLE CAPEX_{{env}}.REVIEWER;
GRANT SELECT ON TABLE CAPEX_{{env}}.CONTROL.CLASSIFICATION_CRITERIA TO DATABASE ROLE CAPEX_{{env}}.REVIEWER;
GRANT SELECT ON TABLE CAPEX_{{env}}.CONTROL.AI_EVAL_RESULTS TO DATABASE ROLE CAPEX_{{env}}.REVIEWER;
-- Decisions are written only through the procedure; no direct INSERT/UPDATE/DELETE on history.
GRANT USAGE ON PROCEDURE CAPEX_{{env}}.REVIEW.RECORD_DECISION(VARCHAR, VARCHAR, VARCHAR, VARCHAR) TO DATABASE ROLE CAPEX_{{env}}.REVIEWER;

-- ---------- PIPELINE_OBSERVER ----------
GRANT USAGE ON DATABASE CAPEX_{{env}} TO DATABASE ROLE CAPEX_{{env}}.PIPELINE_OBSERVER;
{% for s in ['BRONZE', 'SILVER', 'CONTROL'] %}
GRANT USAGE ON SCHEMA CAPEX_{{env}}.{{s}} TO DATABASE ROLE CAPEX_{{env}}.PIPELINE_OBSERVER;
{% endfor %}
GRANT SELECT ON TABLE CAPEX_{{env}}.BRONZE.RAW_RECORDS TO DATABASE ROLE CAPEX_{{env}}.PIPELINE_OBSERVER;
GRANT SELECT ON TABLE CAPEX_{{env}}.CONTROL.INGEST_RUN_LOG TO DATABASE ROLE CAPEX_{{env}}.PIPELINE_OBSERVER;
GRANT SELECT ON TABLE CAPEX_{{env}}.CONTROL.DEPLOYMENT_LOG TO DATABASE ROLE CAPEX_{{env}}.PIPELINE_OBSERVER;
GRANT SELECT ON VIEW CAPEX_{{env}}.CONTROL.INGEST_STATUS TO DATABASE ROLE CAPEX_{{env}}.PIPELINE_OBSERVER;
{% for t in ['PROJECT', 'COST_LINE', 'WORK_ITEM', 'SERVICENOW_RECORD', 'COST_LINE_EVIDENCE', 'DQ_EXCEPTIONS'] %}
GRANT SELECT ON DYNAMIC TABLE CAPEX_{{env}}.SILVER.{{t}} TO DATABASE ROLE CAPEX_{{env}}.PIPELINE_OBSERVER;
{% endfor %}

-- ---------- Functional role mapping ----------
GRANT DATABASE ROLE CAPEX_{{env}}.REVIEWER TO ROLE CAPEX_FIN_REVIEWER;
GRANT DATABASE ROLE CAPEX_{{env}}.GOLD_READER TO ROLE CAPEX_FIN_ANALYST;
GRANT DATABASE ROLE CAPEX_{{env}}.GOLD_READER TO ROLE CAPEX_PMO_ANALYST;
GRANT DATABASE ROLE CAPEX_{{env}}.GOLD_READER TO ROLE CAPEX_ITSEC_ANALYST;
GRANT DATABASE ROLE CAPEX_{{env}}.PIPELINE_OBSERVER TO ROLE CAPEX_DATA_ENG;
-- In DEV, engineers additionally hold CAPEX_DEV_DEPLOYER (granted in platform setup).
-- In UAT/PROD they are observers only: changes arrive exclusively through the CI/CD deployer.
