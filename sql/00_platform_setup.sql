-- One-time platform setup (run as ACCOUNTADMIN). Not promoted by CI/CD.
-- Creates per-environment databases, warehouses and deployer roles.
-- Next: sql/01_cicd_service_users.sql (GitHub Actions identities).

USE ROLE ACCOUNTADMIN;

-- EDIT THIS (optional): the person who builds in DEV and runs the demo. Defaults to you.
SET DEMO_USER = CURRENT_USER();

-- Functional (team) roles
CREATE ROLE IF NOT EXISTS CAPEX_DATA_ENG;
CREATE ROLE IF NOT EXISTS CAPEX_FIN_REVIEWER;
CREATE ROLE IF NOT EXISTS CAPEX_FIN_ANALYST;
CREATE ROLE IF NOT EXISTS CAPEX_PMO_ANALYST;
CREATE ROLE IF NOT EXISTS CAPEX_ITSEC_ANALYST;
GRANT ROLE CAPEX_DATA_ENG      TO ROLE SYSADMIN;
GRANT ROLE CAPEX_FIN_REVIEWER  TO ROLE SYSADMIN;
GRANT ROLE CAPEX_FIN_ANALYST   TO ROLE SYSADMIN;
GRANT ROLE CAPEX_PMO_ANALYST   TO ROLE SYSADMIN;
GRANT ROLE CAPEX_ITSEC_ANALYST TO ROLE SYSADMIN;

GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE CAPEX_DATA_ENG;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE CAPEX_FIN_REVIEWER;

-- Per-environment objects
EXECUTE IMMEDIATE $$
DECLARE
  envs ARRAY DEFAULT ARRAY_CONSTRUCT('DEV','UAT','PROD');
  e STRING;
BEGIN
  FOR i IN 0 TO ARRAY_SIZE(:envs) - 1 DO
    e := envs[i];
    EXECUTE IMMEDIATE 'CREATE ROLE IF NOT EXISTS CAPEX_' || e || '_DEPLOYER';
    EXECUTE IMMEDIATE 'GRANT ROLE CAPEX_' || e || '_DEPLOYER TO ROLE SYSADMIN';
    EXECUTE IMMEDIATE 'CREATE DATABASE IF NOT EXISTS CAPEX_' || e || ' COMMENT = ''CapEx/OpEx review - ' || e || '''';
    EXECUTE IMMEDIATE 'GRANT OWNERSHIP ON DATABASE CAPEX_' || e || ' TO ROLE CAPEX_' || e || '_DEPLOYER COPY CURRENT GRANTS';
    EXECUTE IMMEDIATE 'CREATE WAREHOUSE IF NOT EXISTS CAPEX_' || e || '_WH WAREHOUSE_SIZE=XSMALL AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE';
    EXECUTE IMMEDIATE 'GRANT USAGE, OPERATE ON WAREHOUSE CAPEX_' || e || '_WH TO ROLE CAPEX_' || e || '_DEPLOYER';
    EXECUTE IMMEDIATE 'GRANT EXECUTE TASK, EXECUTE MANAGED TASK ON ACCOUNT TO ROLE CAPEX_' || e || '_DEPLOYER';
    EXECUTE IMMEDIATE 'GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE CAPEX_' || e || '_DEPLOYER';
    EXECUTE IMMEDIATE 'GRANT APPLY MASKING POLICY ON ACCOUNT TO ROLE CAPEX_' || e || '_DEPLOYER';
    EXECUTE IMMEDIATE 'GRANT CREATE ROLE ON ACCOUNT TO ROLE CAPEX_' || e || '_DEPLOYER';
    EXECUTE IMMEDIATE 'GRANT ROLE CAPEX_' || e || '_DEPLOYER TO USER "' || $DEMO_USER || '"';
    EXECUTE IMMEDIATE 'CREATE SCHEMA IF NOT EXISTS CAPEX_' || e || '.DCM';
    EXECUTE IMMEDIATE 'GRANT OWNERSHIP ON SCHEMA CAPEX_' || e || '.DCM TO ROLE CAPEX_' || e || '_DEPLOYER COPY CURRENT GRANTS';
    -- Team roles can use each environment's warehouse; data access comes from database roles.
    EXECUTE IMMEDIATE 'GRANT USAGE ON WAREHOUSE CAPEX_' || e || '_WH TO ROLE CAPEX_FIN_REVIEWER';
    EXECUTE IMMEDIATE 'GRANT USAGE ON WAREHOUSE CAPEX_' || e || '_WH TO ROLE CAPEX_FIN_ANALYST';
    EXECUTE IMMEDIATE 'GRANT USAGE ON WAREHOUSE CAPEX_' || e || '_WH TO ROLE CAPEX_PMO_ANALYST';
    EXECUTE IMMEDIATE 'GRANT USAGE ON WAREHOUSE CAPEX_' || e || '_WH TO ROLE CAPEX_ITSEC_ANALYST';
    EXECUTE IMMEDIATE 'GRANT USAGE ON WAREHOUSE CAPEX_' || e || '_WH TO ROLE CAPEX_DATA_ENG';
  END FOR;
  RETURN 'ok';
END;
$$;

-- Dev is the only env humans build in directly
GRANT ROLE CAPEX_DEV_DEPLOYER TO ROLE CAPEX_DATA_ENG;
GRANT ROLE CAPEX_DATA_ENG TO USER IDENTIFIER($DEMO_USER);
GRANT ROLE CAPEX_FIN_REVIEWER TO USER IDENTIFIER($DEMO_USER);
GRANT ROLE CAPEX_FIN_ANALYST TO USER IDENTIFIER($DEMO_USER);
GRANT ROLE CAPEX_PMO_ANALYST TO USER IDENTIFIER($DEMO_USER);
GRANT ROLE CAPEX_ITSEC_ANALYST TO USER IDENTIFIER($DEMO_USER);
